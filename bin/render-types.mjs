// @ts-check
/**
 * Renders a project's flags as a TypeScript module (LAT-77). Pure: the same
 * flags always give the same text, so re-running latch-generate is a no-op
 * when nothing changed in Latch.
 */

/** @typedef {"boolean" | "string" | "number" | "json"} FlagKind */
/** @typedef {{ key: string, kind: FlagKind, name?: string, values?: unknown[] }} FlagDefinition */

const KINDS = new Set(["boolean", "string", "number", "json"]);

/** "perks.hero-image" → "PerksHeroImage" */
export function constName(key) {
  const name = key
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
  return /^[0-9]/.test(name) ? `Flag${name}` : name;
}

/** The value type a flag's kind (and, for strings, its allowed values) gives. */
function valueType(flag) {
  if (flag.kind === "boolean") return "boolean";
  if (flag.kind === "number") return "number";
  if (flag.kind === "json") return "unknown";
  const values = (flag.values ?? [])
    .map((v) => (typeof v === "object" && v !== null && "value" in v ? /** @type {{ value: unknown }} */ (v).value : v))
    .filter((v) => typeof v === "string");
  return values.length ? [...new Set(values)].sort().map((v) => JSON.stringify(v)).join(" | ") : "string";
}

/**
 * @param {string} project Latch project key the flags came from
 * @param {FlagDefinition[]} flags
 * @returns {string}
 */
export function renderTypes(project, flags) {
  const sorted = [...flags].sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
  const names = new Map();
  for (const flag of sorted) {
    if (!KINDS.has(flag.kind)) throw new Error(`Flag ${flag.key} has an unknown kind: ${flag.kind}`);
    const name = constName(flag.key);
    if (names.has(name)) throw new Error(`Flags ${names.get(name)} and ${flag.key} both become ${name}; rename one in Latch.`);
    names.set(name, flag.key);
  }
  const lines = [
    `// Generated by latch-generate from Latch project "${project}". Do not edit by hand:`,
    "// change flags in Latch and run latch-generate again.",
    "",
    "/** Every flag in the project, by a readable name. */",
    "export const LatchFlag = {",
    ...sorted.map((f) => `  ${constName(f.key)}: ${JSON.stringify(f.key)},`),
    "} as const;",
    "",
    "export type LatchFlagKey = (typeof LatchFlag)[keyof typeof LatchFlag];",
    "",
    "/** Each flag's kind. */",
    "export const LatchFlagKind = {",
    ...sorted.map((f) => `  ${JSON.stringify(f.key)}: ${JSON.stringify(f.kind)},`),
    '} as const satisfies Record<LatchFlagKey, "boolean" | "string" | "number" | "json">;',
    "",
    "/** The value each flag evaluates to. */",
    "export interface LatchFlagValues {",
    ...sorted.map((f) => `  ${JSON.stringify(f.key)}: ${valueType(f)};`),
    "}",
    "",
    "/** Keys of the on/off flags. */",
    "export type LatchBooleanFlagKey = {",
    "  [K in LatchFlagKey]: LatchFlagValues[K] extends boolean ? K : never;",
    "}[LatchFlagKey];",
    "",
  ];
  return lines.join("\n");
}
